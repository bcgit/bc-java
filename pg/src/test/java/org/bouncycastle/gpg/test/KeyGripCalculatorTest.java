package org.bouncycastle.gpg.test;

import java.io.OutputStream;
import java.math.BigInteger;

import org.bouncycastle.bcpg.BCPGKey;
import org.bouncycastle.bcpg.HashAlgorithmTags;
import org.bouncycastle.bcpg.RSAPublicBCPGKey;
import org.bouncycastle.crypto.digests.SHA1Digest;
import org.bouncycastle.crypto.digests.SHA256Digest;
import org.bouncycastle.gpg.KeyGripCalculator;
import org.bouncycastle.openpgp.operator.PGPDigestCalculator;
import org.bouncycastle.util.Arrays;
import org.bouncycastle.util.BigIntegers;
import org.bouncycastle.util.encoders.Hex;
import org.bouncycastle.util.test.SimpleTest;

public class KeyGripCalculatorTest
    extends SimpleTest
{
    public String getName()
    {
        return "KeyGripCalculator";
    }

    public void performTest()
        throws Exception
    {
        rsaKeygripMatchesSha1OfModulus();
        wrongAlgorithmRejected();
        unsupportedKeyTypeRejected();
    }

    private void rsaKeygripMatchesSha1OfModulus()
        throws Exception
    {
        // RSA-2048 key generated by GnuPG 2.4.4 / libgcrypt 1.10.3, keygrip as printed by gpg --with-keygrip
        BigInteger n = new BigInteger(
            "A859DCDD5C06C342BCDD32A2EEB2A6150F1E5388D5052D523B9DA833A086A9F9" +
            "DFCCE5633EF71F7BCEE9330028DA5187CB5B9BA5F37DB5DDA40BE378729A3094" +
            "EE13BB0FEA91D76F5232CB0BF6A914E62D3F0060C29FF8AE829804C0BFF5D20C" +
            "728D7A45A372885E8CC1B928F144088C367BA6C00D2733A05BD34C2137A5C3BC" +
            "0324910A3B1CC26998A5FE67810086CC40132BEDA399EEEAED73B394EEE54A9E" +
            "03BD7FBFA46BEC33DB6BEA13F7008439E046B18B7E968BE94EDF058F8BE99EF0" +
            "91FEFBB7A0670302A0743B99B4F052559192A94CA5616CCE8353F35E6450C78C" +
            "BEAF8DE297DE692A6EE907FB3F4413BFC86BE715143C68FB21360EED0B8F37E1", 16);
        BigInteger e = BigInteger.valueOf(65537);

        byte[] grip = new KeyGripCalculator(sha1()).calculateKeygrip(new RSAPublicBCPGKey(n, e));

        if (!Arrays.areEqual(Hex.decode("2C8B572DDA6A6EA8C972F38D23B74DC1D381AD0E"), grip))
        {
            fail("RSA keygrip did not match GnuPG");
        }

        // a modulus with its top bit clear is hashed without a leading zero byte (libgcrypt's signed MPI format)
        BigInteger shortN = n.clearBit(n.bitLength() - 1).setBit(n.bitLength() - 2);
        byte[] shortNBytes = BigIntegers.asUnsignedByteArray(shortN);
        SHA1Digest md = new SHA1Digest();
        md.update(shortNBytes, 0, shortNBytes.length);
        byte[] expected = new byte[md.getDigestSize()];
        md.doFinal(expected, 0);

        if (!Arrays.areEqual(expected, new KeyGripCalculator(sha1()).calculateKeygrip(new RSAPublicBCPGKey(shortN, e))))
        {
            fail("RSA keygrip wrong for modulus with top bit clear");
        }
    }

    private void wrongAlgorithmRejected()
    {
        try
        {
            new KeyGripCalculator(sha256());
            fail("expected IllegalArgumentException for non-SHA1 digest calculator");
        }
        catch (IllegalArgumentException expected)
        {
            // expected
        }
    }

    private void unsupportedKeyTypeRejected()
        throws Exception
    {
        BCPGKey unsupported = new BCPGKey()
        {
            public String getFormat()
            {
                return "PGP";
            }

            public byte[] getEncoded()
            {
                return new byte[0];
            }
        };

        try
        {
            new KeyGripCalculator(sha1()).calculateKeygrip(unsupported);
            fail("expected IllegalArgumentException for unsupported key type");
        }
        catch (IllegalArgumentException expected)
        {
            // expected
        }
    }

    private static PGPDigestCalculator sha1()
    {
        return new SimpleDigestCalculator(HashAlgorithmTags.SHA1, new SHA1Digest());
    }

    private static PGPDigestCalculator sha256()
    {
        return new SimpleDigestCalculator(HashAlgorithmTags.SHA256, new SHA256Digest());
    }

    private static class SimpleDigestCalculator
        implements PGPDigestCalculator
    {
        private final int algorithm;
        private final org.bouncycastle.crypto.Digest digest;
        private final OutputStream stream;

        SimpleDigestCalculator(int algorithm, final org.bouncycastle.crypto.Digest digest)
        {
            this.algorithm = algorithm;
            this.digest = digest;
            this.stream = new OutputStream()
            {
                public void write(int b)
                {
                    digest.update((byte)b);
                }

                public void write(byte[] buf, int off, int len)
                {
                    digest.update(buf, off, len);
                }
            };
        }

        public int getAlgorithm()
        {
            return algorithm;
        }

        public OutputStream getOutputStream()
        {
            return stream;
        }

        public byte[] getDigest()
        {
            byte[] out = new byte[digest.getDigestSize()];
            digest.doFinal(out, 0);
            return out;
        }

        public void reset()
        {
            digest.reset();
        }
    }

    public static void main(String[] args)
    {
        runTest(new KeyGripCalculatorTest());
    }
}
